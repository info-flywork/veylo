const byTurkish = new Map<string, VibeLine>();
for (const lines of Object.values(PERSONA_VIBES)) {
  for (const line of lines) byTurkish.set(line.tr, line);
}

function localeOf(code: string): (typeof ENUMS.languages)[number] {
  return (ENUMS.languages as readonly string[]).includes(code) ? (code as (typeof ENUMS.languages)[number]) : 'en';
}

/** Kayıtlı Türkçe metni, bakan kişinin diline çevirir. Tanınmayan metin aynı karakterin satırından gelir. */
export function personaVibeBody(stored: string, locale: string, vibeId: string, username: string | null) {
  const lang = localeOf(locale);
  const known = byTurkish.get(stored);
  if (known) return known[lang];
  const pool = (username && PERSONA_VIBES[username]) || Object.values(PERSONA_VIBES).flat();
  if (pool.length === 0) return stored;
  let n = 0;
  for (const ch of vibeId) n = (n + ch.charCodeAt(0)) % pool.length;
  return pool[n]![lang];
}

export function turkishVibeLines(username: string | null) {
  const pool = (username && PERSONA_VIBES[username]) || Object.values(PERSONA_VIBES).flat();
  return pool.map((line) => line.tr);
}
